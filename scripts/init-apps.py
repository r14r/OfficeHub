"""Generate strong per-app secrets without overwriting existing environment values."""
from pathlib import Path
import secrets

env = Path(".env")
if not env.exists():
    raise SystemExit("Run just init first to create .env")
keys = ["PAPERLESS_DB_PASSWORD","PAPERLESS_SECRET_KEY","N8N_DB_PASSWORD","N8N_ENCRYPTION_KEY","DOCUSEAL_DB_PASSWORD","KIMAI_DB_PASSWORD","KIMAI_ROOT_PASSWORD","KIMAI_APP_SECRET","KIMAI_ADMIN_PASSWORD","AUTHENTIK_DB_PASSWORD","AUTHENTIK_SECRET_KEY","VIKUNJA_DB_PASSWORD","VIKUNJA_SECRET","TWENTY_DB_PASSWORD","TWENTY_APP_SECRET","TWENTY_ENCRYPTION_KEY","AKAUNTING_DB_PASSWORD","AKAUNTING_ROOT_PASSWORD","AKAUNTING_APP_KEY","NINJA_DB_PASSWORD","NINJA_ROOT_PASSWORD","AUTOMATISCH_DB_PASSWORD","AUTOMATISCH_ENCRYPTION_KEY","AUTOMATISCH_WEBHOOK_SECRET_KEY","AUTOMATISCH_APP_SECRET_KEY"]
present = {line.split("=", 1)[0] for line in env.read_text().splitlines() if "=" in line and not line.startswith("#")}
additions = [f"{key}={secrets.token_hex(32)}" for key in keys if key not in present]
if "NINJA_APP_KEY" not in present:
    import base64
    additions.append("NINJA_APP_KEY=base64:" + base64.b64encode(secrets.token_bytes(32)).decode("ascii"))
if additions:
    with env.open("a") as f:
        f.write("\n# Optional application secrets (generated by just apps-init)\n")
        f.write("\n".join(additions) + "\n")
    env.chmod(0o600)
print(f"Application environment ready; created {len(additions)} missing secrets")
